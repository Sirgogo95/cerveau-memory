# Social authentication (allauth). Two modes, enforced in Environment.validate():
#   - OIDC (oidc_client): a full SSO lockdown. Login is required on every view
#     and the portal is the ONLY way in (no local login). Exclusive with the rest.
#   - Additional logins (google_client and/or microsoft_client): extra buttons on
#     Django's default login page. They coexist with each other and with
#     username/password login, and never lock anything down.
#
# The block below is only the common allauth wiring; the lockdown pieces live in
# the OIDC-specific branch, and each additional provider adds itself to
# SOCIALACCOUNT_PROVIDERS in its own branch.
if ACTIVE.activate_oidc_client_auth or ACTIVE.activate_additional_login:
    INSTALLED_APPS.extend(
        [
            "allauth",
            "allauth.account",
            "allauth.socialaccount",
        ]
    )
    MIDDLEWARE += ["allauth.account.middleware.AccountMiddleware"]

    # Silently create/link a local user by email on social login (no signup form).
    SOCIALACCOUNT_AUTO_SIGNUP = True
    ACCOUNT_EMAIL_VERIFICATION = "none"
    SOCIALACCOUNT_EMAIL_AUTHENTICATION = (
        True  # match existing local users by email (see note below)
    )
    SOCIALACCOUNT_EMAIL_AUTHENTICATION_AUTO_CONNECT = (
        True  # auto-connect to existing local user by email
    )
    LOGIN_REDIRECT_URL = "/"
    SOCIALACCOUNT_PROVIDERS = {}

if ACTIVE.activate_oidc_client_auth:
    INSTALLED_APPS.append("allauth.socialaccount.providers.openid_connect")

    # Require login on every view; opt out per-view with @login_not_required.
    # allauth and the admin login page exempt themselves.
    target_index = MIDDLEWARE.index(
        "django.contrib.messages.middleware.MessageMiddleware"
    )
    MIDDLEWARE.insert(
        target_index, "django.contrib.auth.middleware.LoginRequiredMiddleware"
    )

    # Portal is the ONLY way in: disable allauth's local username/password login,
    # signup, and password management. The Django admin keeps its own /admin/login/
    # for break-glass superuser access.
    SOCIALACCOUNT_ONLY = True
    SOCIALACCOUNT_LOGIN_ON_GET = (
        True  # skip the "Continue with the provider?" confirmation page
    )

    # Map portal roles/groups onto Django permissions (is_staff / is_superuser /
    # groups). This runs only under OIDC; see kernel/base_app/adapters.py. The matching
    # role-sync signals are connected in BaseAppConfig.ready() gated on OIDC_ROLE_SYNC.
    SOCIALACCOUNT_ADAPTER = "kernel.base_app.adapters.OIDCRoleAdapter"
    OIDC_ROLE_SYNC = True

    SOCIALACCOUNT_PROVIDERS["openid_connect"] = {
        "APPS": [
            ACTIVE.as_django_settings()["OIDC_CLIENT_APP"],
        ]
    }
    # Send unauthenticated users straight to the portal instead of a local login form.
    # allauth's OIDC login route is /accounts/oidc/<provider_id>/login/, so derive it
    # from the provider id rather than hard-coding the slug (which drifts out of sync).
    LOGIN_URL = f"/accounts/oidc/{ACTIVE.oidc_client.provider_id}/login/"

if ACTIVE.activate_additional_login:
    # Google / Microsoft are ADDITIONAL login options. We deliberately do NOT set
    # SOCIALACCOUNT_ONLY, LoginRequiredMiddleware, or a custom LOGIN_URL, so
    # Django's default login (allauth's /accounts/login/ form and the admin) stays
    # available. Each enabled provider appears as a button on that standard page.
    #
    # Both log in existing users (matched by verified email) but never create new
    # accounts; see kernel.base_app.adapters.PortalSocialAccountAdapter.
    SOCIALACCOUNT_ADAPTER = "kernel.base_app.adapters.PortalSocialAccountAdapter"

if ACTIVE.activate_google_auth:
    INSTALLED_APPS.append("allauth.socialaccount.providers.google")
    SOCIALACCOUNT_PROVIDERS["google"] = {
        "APP": ACTIVE.as_django_settings()["GOOGLE_CLIENT_APP"],
        "SCOPE": ["profile", "email"],
        "AUTH_PARAMS": {"access_type": "online"},
    }

if ACTIVE.activate_microsoft_auth:
    INSTALLED_APPS.append("allauth.socialaccount.providers.microsoft")
    SOCIALACCOUNT_PROVIDERS["microsoft"] = {
        # The tenant lives in APP["settings"]["tenant"] (see MicrosoftClientAppSettings).
        "APP": ACTIVE.as_django_settings()["MICROSOFT_CLIENT_APP"],
        # Microsoft Graph returns no email_verified claim, so allauth would treat the
        # address as unverified and SOCIALACCOUNT_EMAIL_AUTHENTICATION could not match
        # it to a local user. Work/school addresses are controlled by the tenant, so we
        # trust them. Narrow this to a list of domains to trust only some, e.g.
        # ["example.com"]; any other address is then refused (no signup).
        "VERIFIED_EMAIL": True,
    }
